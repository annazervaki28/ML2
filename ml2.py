# Initialize the results list
results_data = []

def log_results(dim_red_name, cluster_alg_name, train_time, exec_time,
                n_clusters, ch_score, db_score, sil_score, custom_metric):
    """
    Appends performance metrics to the global results list.
    """
    results_data.append({
        "Dim. Red. Technique": dim_red_name,
        "Clustering Algorithm": cluster_alg_name,
        "Training Time (s)": round(train_time, 4),
        "Execution Time (s)": round(exec_time, 4),
        "Suggested Clusters": n_clusters,
        "Calinski-Harabasz": round(ch_score, 4),
        "Davies-Bouldin": round(db_score, 4),
        "Silhouette": round(sil_score, 4),
        "Adjusted Rand Index": round(custom_metric, 4) # Our 4th metric choice
    })

