tsvd = TruncatedSVD(n_components=50, random_state=42)
tsvd.fit(x_train_flat)
tsvd_train_time = time.time() - start_time
x_test_tsvd = tsvd.transform(x_test_flat)

# --- 4th Metric Selection: Adjusted Rand Index (ARI) ---
# ARI compares clusters with the real labels (y_test)
# Score: 1.0 is perfect, 0.0 is random.

# Dictionary to hold our transformed datasets
datasets = {
    "Raw": x_test_flat,
    "PCA": x_test_pca,
    "SAE": x_test_sae,
    "TruncatedSVD": x_test_tsvd
}

# Training times for Dim. Red. (recorded during their fits)
dim_red_times = {
    "Raw": 0.0,
    "PCA": pca_train_time,
    "SAE": sae_train_time,
    "TruncatedSVD": tsvd_train_time
}

def run_clustering_suite(data_name, data_encoded, labels_true):
    print(f"\nProcessing Dataset: {data_name}")

    # Define Clustering Algorithms
    # 1. MiniBatchKMeans (Required)
    # 2. DBSCAN (Required)
    # 3. GMM (Choice)
    algorithms = {
        "MiniBatchKMeans": MiniBatchKMeans(n_clusters=10, batch_size=256, random_state=42),
        "DBSCAN": DBSCAN(eps=0.5, min_samples=5), # Parameters might need tuning
        "GMM": GaussianMixture(n_components=10, random_state=42)
    }

    for alg_name, model in algorithms.items():
        print(f"  Running {alg_name}...")

        start_exec = time.time()
        if alg_name == "GMM":
            cluster_labels = model.fit_predict(data_encoded)
        else:
            cluster_labels = model.fit_predict(data_encoded)
        exec_time = time.time() - start_exec

        # Number of clusters (DBSCAN might find more or less than 10)
        n_clusters = len(set(cluster_labels)) - (1 if -1 in cluster_labels else 0)

        # Performance Metrics (using a sample for Silhouette to save time)
        if n_clusters > 1:
            ch_idx = metrics.calinski_harabasz_score(data_encoded, cluster_labels)
            db_idx = metrics.davies_bouldin_score(data_encoded, cluster_labels)

            # Sampling for speed
            sample_indices = np.random.choice(len(data_encoded), size=min(2000, len(data_encoded)), replace=False)
            sil_score = metrics.silhouette_score(data_encoded[sample_indices], cluster_labels[sample_indices])

            ari_score = metrics.adjusted_rand_score(labels_true, cluster_labels)
        else:
            ch_idx, db_idx, sil_score, ari_score = 0, 0, 0, 0

        # Log results to the list
        log_results(data_name, alg_name, dim_red_times[data_name], exec_time,
                    n_clusters, ch_idx, db_idx, sil_score, ari_score)

# Execute the loop for all 4 data versions
for name, data in datasets.items():
    run_clustering_suite(name, data, y_test)

