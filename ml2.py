# 2. Function to plot the grid
def plot_cluster_grid(data_images, labels, n_clusters=4):
    plt.figure(figsize=(15, 10))
    # Select the first 4 clusters to display
    selected_clusters = [0, 1, 2, 3]

    for i, cluster_id in enumerate(selected_clusters):
        # Get indices of images in this cluster
        cluster_indices = np.where(labels == cluster_id)[0]

        # Pick 5 random images from this cluster
        if len(cluster_indices) >= 5:
            sample_indices = np.random.choice(cluster_indices, 5, replace=False)
        else:
            sample_indices = cluster_indices # If cluster is very small

        for j, img_idx in enumerate(sample_indices):
            plt.subplot(n_clusters, 5, i * 5 + j + 1)
            # Ensure we reshape to 28x28 for display
            plt.imshow(data_images[img_idx].reshape(28, 28), cmap='gray')
            if j == 0:
                plt.ylabel(f"Cluster {cluster_id}", fontsize=14, fontweight='bold')
            plt.axis('off')

    plt.suptitle("Indicative Grouping Results (SAE + MiniBatchKMeans)", fontsize=16)
    plt.tight_layout(rect=[0, 0.03, 1, 0.95])
    plt.show()

# Run the plotting function
